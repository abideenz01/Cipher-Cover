from decimal import Decimal

from sqlalchemy.pool import QueuePool

from agent import checkpoints
from backend import db


def test_placeholders_become_named_and_colons_stay_literal():
    query, names = db.statement("SELECT ? || 'at 12:30' WHERE a = ? AND b = ?")
    assert names == ("p0", "p1", "p2")
    assert str(query) == "SELECT :p0 || 'at 12:30' WHERE a = :p1 AND b = :p2"


def test_booleans_are_stored_as_integers():
    assert db.bind(("p0", "p1", "p2"), (True, False, "x")) == {
        "p0": 1,
        "p1": 0,
        "p2": "x",
    }


def test_postgres_sums_come_back_as_sqlite_would_give_them():
    assert db.plain(Decimal(140000)) == 140000
    assert isinstance(db.plain(Decimal(140000)), int)
    assert db.plain(Decimal("1.5")) == 1.5
    assert db.plain("x") == "x"


def test_rows_read_by_name_position_and_slice_like_sqlite3():
    row = db.Row(["a", "b"], [1, Decimal(2)])
    assert row["a"] == 1
    assert row[1] == 2
    assert row[:2] == [1, 2]
    assert tuple(row) == (1, 2)
    assert dict(row) == {"a": 1, "b": 2}
    assert len(row) == 2


def test_integer_keys_count_up_on_postgres():
    sql = "CREATE TABLE t (id INTEGER PRIMARY KEY, n TEXT)"
    assert db.ddl(sql, "sqlite") == sql
    assert db.ddl(sql, "postgresql") == (
        "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
        " n TEXT)"
    )


def test_sqlite_without_database_url(monkeypatch):
    monkeypatch.delenv("DATABASE_URL", raising=False)
    assert not db.postgres()
    assert db.engine().dialect.name == "sqlite"


def test_postgres_with_database_url_holds_at_most_four_connections(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", "postgresql://u:p@127.0.0.1:1/x")
    made = db.engine()
    assert made.dialect.name == "postgresql"
    assert made.dialect.driver == "psycopg"
    pool = made.pool
    assert isinstance(pool, QueuePool)
    assert pool.size() + checkpoints.CONNECTIONS == 4
    assert pool._max_overflow == 0  # noqa: SLF001 - no public accessor


def test_an_empty_database_url_means_sqlite(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", "")
    assert not db.postgres()


def test_a_failed_block_writes_nothing():
    try:
        with db.connect() as conn:
            conn.execute("UPDATE claims SET state = 'decided'")
            raise RuntimeError
    except RuntimeError:
        pass
    with db.connect() as conn:
        states = conn.execute("SELECT DISTINCT state FROM claims").fetchall()
    assert [r["state"] for r in states] == ["waiting"]


def test_executemany_with_no_rows_does_nothing():
    with db.connect() as conn:
        conn.executemany("INSERT INTO reference VALUES (?, ?)", [])
